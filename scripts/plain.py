def stage_of_dayun(day_gan, dayun_gan):
    """日干在某一步大运干上处于十二长生的第几格。

    十二长生是**干支纪年体系**里的记号，刻度是十二个**地支**，
    不是天干。所以正确算法是：以「日干的长生支」为起点，
    按「大运干与日干同阴阳则顺行、异阴阳则逆行」，
    数到「大运干自己的长生支」落在第几格。

        日干庚（阳金，长生在巳）
          大运壬（阳水，长生在申）：顺行 巳→午→未→申 = 第 3 格 = 冠带
          大运乙（阴木，长生在午）：逆行 巳→辰→卯→寅→丑→子→亥→戌→酉→申→未→午 = 第 11 格 = 养

    **踩过的坑**：一开始写成「按天干五行相生相克推一步或两步」，
    结果只能落在长生/沐浴/冠带/胎/养 5 格里 —— 自检里
    「十二长生必须覆盖全部 12 格」直接就抓出来了。
    天干之间隔着「相生 +1 / 相克 +2」这种关系，跟十二长生的
    地支轮转根本不是一回事。刻度必须用地支。
    """
    me_yy = GAN_YINYANG[GAN.index(day_gan)] == "阳"
    dy_yy = GAN_YINYANG[GAN.index(dayun_gan)] == "阳"
    me_start = ZHI.index(LONG_ZHI[day_gan])        # 日干的长生支
    dy_start = ZHI.index(LONG_ZHI[dayun_gan])      # 大运干的长生支
    delta = (dy_start - me_start) % 12
    if not me_yy == dy_yy:
        delta = (12 - delta) % 12                  # 异阴阳逆行
    return TWELVE_STAGES[delta]


