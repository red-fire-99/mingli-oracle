def _bazi_cross_ctx(r):
    """把八字原始盘收成交叉判据要用的计数。

    只数**透干**（天干上出现的十神），不算藏干：
    藏干是「暗力量」，六个维度里好几个都靠十神判，
    全部掺进藏干就分不出来了。
    """
    c = {"食伤": 0, "同侪": 0, "守": 0, "变": 0,
         "对宫星": 0, "官杀": 0, "快": 0, "慢": 0}
    for d in r.get("柱详解") or []:
        if d.get("柱") == "日":
            continue
        ss = d.get("干十神")
        if ss in ("食神", "伤官"):
            c["食伤"] += 1
        elif ss in ("比肩", "劫财"):
            c["同侪"] += 1
            c["守"] += 1
        elif ss in ("正印", "偏印"):
            c["守"] += 1
        elif ss in ("正财", "偏财", "正官", "七杀"):
            c["变"] += 1
            c["对宫星"] += 1
        if ss in ("正官", "七杀"):
            c["官杀"] += 1
    pct = r.get("五行统计") or {}
    c["快"] = int(round(pct.get("木", 0) + pct.get("火", 0)))
    c["慢"] = int(round(pct.get("金", 0) + pct.get("水", 0)))
    return c


def _bazi_cross_side(ctx, axis_name):
    """八字在某个维度上的落点。返回 (side, 依据) 或 None。

    判据逐条写死在这里而不是塞进表 —— 每条都要能解释「凭什么」，
    塞进lambda 之后就没法单独审了。
    """
    if ctx is None or axis_name not in CROSS_AXES_BY_NAME:
        return None
    if axis_name == "表达方式":
        n = ctx["食伤"]
        return (0 if n else 1,
                "八字·食伤透干 %d 个" % n if n
                else "八字·食伤不透，思路先在心里过一遍")
    if axis_name == "行动节奏":
        return (0 if ctx["快"] >= ctx["慢"] else 1,
                "八字·木火 %d%% 对金水 %d%%" % (ctx["快"], ctx["慢"]))
    if axis_name == "社交范围":
        n = ctx["同侪"]
        return (0 if n else 1,
                "八字·比劫透干 %d 个" % n if n
                else "八字·比劫不显，圈子偏小而固定")
    if axis_name == "守旧与换新":
        return (0 if ctx["守"] >= ctx["变"] else 1,
                "八字·印比 %d 个 对 食伤财 %d 个" % (ctx["守"], ctx["变"]))
    if axis_name == "关系经营":
        n = ctx["对宫星"]
        return (0 if n else 1,
                "八字·财官透干 %d 个" % n if n
                else "八字·财官不显，关系上偏向留有余地")
    if axis_name == "事业路子":
        return (0 if ctx["官杀"] > ctx["食伤"] else 1,
                "八字·官杀 %d 个 对 食伤 %d 个" % (ctx["官杀"], ctx["食伤"]))
    return None


