def wuxing_imagery(stat, xiyong):
    """把五行统计翻成「哪股劲儿最足 / 最缺」的清单。

    stat:   {"木": 5.0, "火": 34.2, ...}
    xiyong: 喜用神列表

    返回 (最强 dict, 最弱 dict 或 None, 全量列表)
    """
    if not stat:
        return None, None, []
    total = sum(v for v in stat.values() if v > 0) or 1.0
    items = []
    for w, v in stat.items():
        info = WUXING_IMAGERY.get(w, {})
        items.append({
            "五行": w, "象": info.get("象", ""),
            "占比": round(v / total * 100, 1), "力量": v,
            "描述": info.get("描述", ""),
            "偏多时": info.get("多", ""), "偏少时": info.get("少", ""),
            "是喜用": w in (xiyong or []),
        })
    items.sort(key=lambda x: -x["力量"])
    strongest = items[0] if items else None
    weakest = items[-1] if len(items) > 1 else None
    if weakest is not None and weakest["力量"] <= 0:
        weakest = None
    return strongest, weakest, items


