def _kin_list(r):
    """八字六亲：谁是哪颗星、透不透、落在哪一柱。

    男女分派是硬要求 —— 同盘只差性别，不分派的话男女看到同一段话。
    """
    sex = (r.get("输入") or {}).get("性别") or "男"
    if sex not in KIN_STARS:
        sex = "男"
    cols = r.get("柱详解") or []

    # 干上/支里的十神出现位置。柱序固定：年 月 日 时。
    place = {}
    for c in cols:
        p = c.get("柱")
        g = c.get("干十神")
        if g and g != "日主":
            place.setdefault(g, []).append({"柱": p, "位": "干", "干支": c.get("干")})
        for z in (c.get("支藏干") or []):
            s = z.get("十神")
            if s:
                place.setdefault(s, []).append(
                    {"柱": p, "位": "支", "干支": c.get("支"), "藏": z.get("干")})

    items = []
    for role in ("配偶", "父母", "兄弟", "子女"):
        stars = KIN_STARS[sex][role]
        got = []
        for st in stars:
            for it in place.get(st) or []:
                d = dict(it)
                d["十神"] = st
                d["透"] = it["位"] == "干"
                got.append(d)
        # 先透后藏，同为透/藏时按柱序（年→月→日→时）
        order = {"年柱": 0, "月柱": 1, "日柱": 2, "时柱": 3}
        got.sort(key=lambda x: (0 if x["透"] else 1, order.get(x["柱"], 9)))
        items.append({
            "角色": role,
            "星": stars,
            "个数": len(got),
            "位置": got,
            "有透": any(x["透"] for x in got),
            "说明": KIN_ROLE_NOTE[sex][role],
        })

    # 柱位对应单独给一份（四柱都摆出来，不是每个角色重复一遍）
    pillars = [{"柱": c.get("柱"), "干支": c.get("干") + (c.get("支") or ""),
                "代表": PILLAR_ROLE.get(c.get("柱"), "")} for c in cols]
    return {"标题": "六亲怎么看", "口径": KIN_CAVEAT, "列表": items,
            "柱位": pillars, "性别": sex}


def _spouse_list(r):
    """紫微夫妻宫：主星组合、煞星、大限何时走到、对宫是谁。

    这一块最容易顺嘴写成断语（「婚姻不顺」），所以措辞全部走
    「需要磨合的地方 / 怎么相处」，不走「好 / 坏」。
    """
    pal = {p.get("宫名"): p for p in (r.get("十二宫") or [])}
    fu = pal.get("夫妻")
    if not fu:
        return {"标题": "夫妻宫"}

    zhi = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"]
    z = fu.get("地支")
    opp_name = ""
    if z in zhi:
        opp_z = zhi[(zhi.index(z) + 6) % 12]
        opp_name = next((k for k, v in pal.items() if v.get("地支") == opp_z), "")

    # 主星组合优先。单星兜底。
    #
    # 注意：主星可能带四化后缀（"太阳·化禄"）。
    # 原先直接用 `"·" not in s` 把这些星过滤掉，结果带四化的夫妻宫
    # 主星全空、整块不渲染 —— 而这在夫妻宫有煞星时会被漏掉，
    # 直到时辰路径门禁（用辰时那个盘）才暴露出来。
    # 现在保留完整星名做查表，基名（去掉 · 之后的部分）用于匹配。
    raw_main = fu.get("主星") or []
    main = [s for s in raw_main if s]
    combo = None
    for i in range(len(main)):
        for j in range(i + 1, len(main)):
            a, b = main[i], main[j]
            combo = (SPOUSE_PAIR.get((a, b)) or SPOUSE_PAIR.get((b, a))
                     or SPOUSE_PAIR.get((a.split("·")[0], b.split("·")[0]))
                     or SPOUSE_PAIR.get((b.split("·")[0], a.split("·")[0])))
            if combo:
                combo = {"型": combo[0], "说明": combo[1], "星": [a, b]}
                break
        if combo:
            break
    if not combo and len(main) == 1:
        one = main[0]
        txt = SPOUSE_SINGLE.get(one) or SPOUSE_SINGLE.get(one.split("·")[0])
        if txt:
            combo = {"型": one, "说明": txt, "星": main[:1]}

    # 煞星与其他星，逐个查表。查不到的显式标出来，不静默跳过。
    sha, unknown = [], []
    for s in (fu.get("星曜") or []):
        base = s.split("·")[0]
        if s in raw_main:
            continue
        if base in SPOUSE_SHA:
            sha.append({"星": base, "型": SPOUSE_SHA[base][0], "说明": SPOUSE_SHA[base][1]})
        else:
            unknown.append(s)

    # 主星上的四化要单独讲 —— 它是这块星曜的当前状态，
    # 不是「另一种星」。混进煞星或未解读里都是错的。
    hua = []
    for s in raw_main:
        if "·" in s:
            k = s.split("·", 1)[1]
            role = SIHUA_ROLE.get(k)
            hua.append({"星": s, "化": k,
                        "说明": (role[1] if role else "")})

    # 大限何时走到夫妻宫
    dx = ""
    dx_age = ""
    for x in ((r.get("大限") or {}).get("列表") or []):
        if x.get("宫位") == "夫妻":
            dx_age = "%d–%d" % (x.get("虚岁起"), x.get("虚岁止"))
            try:
                if int(x.get("虚岁起")) >= 45:
                    dx = SPOUSE_DAXIAN_LATE
                else:
                    dx = SPOUSE_DAXIAN_YOUNG
            except (TypeError, ValueError):
                dx = ""
            break

    return {"标题": "夫妻宫", "宫干": fu.get("天干") or "", "地支": z,
            "对宫": opp_name, "主星": main, "组合": combo, "四化": hua,
            "煞星": sha, "未解读": unknown, "大限年龄": dx_age, "大限说明": dx}


