def astro_plain(r):
    """西洋占星白话解读：三支柱 + 性格拼图 + 人生重心 + 元素配比 + 关系张力。"""
    sun = r["太阳星座"]
    moon = r["月亮星座"]
    asc = r.get("上升星座", "未知")
    has_asc = asc in ASC_SIGN

    # 1. 一句话总览
    if has_asc:
        one = ("你的内核是个%s，情感上最需要%s，而别人看到的是一个%s的人。"
               % (SUN_KEYWORD.get(sun, ""), MOON_KEYWORD.get(moon, ""), ASC_KEYWORD.get(asc, "")))
    else:
        one = ("你的内核是个%s，情感上最需要%s。（填了出生地，才能算出上升星座和宫位）"
               % (SUN_KEYWORD.get(sun, ""), MOON_KEYWORD.get(moon, "")))

    # 2. 三大支柱
    pillars = [
        {"名": "太阳 · 你的核心自我", "座": sun, "文": SUN_SIGN.get(sun, "")},
        {"名": "月亮 · 你的情感需求", "座": moon, "文": MOON_SIGN.get(moon, "")},
    ]
    if has_asc:
        pillars.append({"名": "上升 · 别人看到的你", "座": asc, "文": ASC_SIGN.get(asc, "")})

    # 3. 性格拼图：思维 / 爱情 / 行动
    sign_of = {p["天体"]: p["星座"] for p in r["天体"]}
    puzzle = []
    for planet, table, label in (("水星", MERCURY_SIGN, "你怎么想、怎么说"),
                                 ("金星", VENUS_SIGN, "你怎么爱、怎么审美"),
                                 ("火星", MARS_SIGN, "你怎么行动、怎么发火")):
        sg = sign_of.get(planet)
        if sg in table:
            puzzle.append({"名": "%s（%s在%s）" % (label, planet, sg), "座": sg, "文": table[sg]})

    # 4. 人生重心：行星落宫
    house_of = {}
    for h in r.get("宫位", []):
        for p in h["内行星"]:
            house_of[p] = h["宫"]
    focus = []
    for planet in ("太阳", "月亮", "金星", "火星", "木星", "土星"):
        if planet in house_of:
            n = house_of[planet]
            tmpl = HOUSE_BY_PLANET.get(planet)
            if tmpl:
                focus.append({
                    "名": "%s · 落在第 %d 宫（%s）" % (PLANET_ROLE[planet][1], n, HOUSE_MEANING[n]),
                    "文": tmpl % HOUSE_MEANING[n],
                })

    # 5. 元素配比（最多的 + 缺的，都要讲）
    elem = r["元素分布"]
    total = sum(elem.values()) or 1
    top_e = max(elem, key=elem.get)
    missing = [k for k, v in elem.items() if v == 0]
    parts = []
    if elem[top_e] / total >= 0.4:
        parts.append(ELEMENT_MORE[top_e])
    if missing:
        parts.append("另外，你的「%s」元素偏少：%s" % ("、".join(missing), ELEMENT_MISS[missing[0]]))
    if not parts:
        parts.append("你的四元素配比比较均衡，性格立体，什么场合都能适应。")
    e_txt = "".join(parts)

    # 6. 关键线索：上升守护星（命主星）落在哪
    key_clue = None
    if has_asc:
        ruler = RULER.get(asc)
        if ruler:
            r_sign = sign_of.get(ruler)
            r_house = house_of.get(ruler)
            txt = "你的上升在%s，它的守护星是%s" % (asc, ruler)
            if r_sign:
                txt += "（%s在%s）" % (ruler, r_sign)
            if r_house:
                txt += "，落在第 %d 宫（%s）。这是整张盘最关键的一条线索——" \
                       "你这辈子的重要课题，往往跟「%s」有关。" % (r_house, HOUSE_MEANING[r_house], HOUSE_MEANING[r_house])
            else:
                txt += "。这是整张盘最关键的一条线索。"
            key_clue = txt

    # 7. 关系张力：取强度最高的几组相位，用「短职能名」拼成人话
    tension = []
    for a in sorted(r["相位"], key=lambda x: -x["强度"])[:4]:
        p1 = PLANET_ROLE.get(a["天体1"], (a["天体1"], ""))[0]
        p2 = PLANET_ROLE.get(a["天体2"], (a["天体2"], ""))[0]
        trait = ASPECT_TRAIT.get(a["相位"], a["相位"])
        tension.append({"文": "你的「%s」和「%s」%s。" % (p1, p2, trait)})

    # 8. 星座实用档案（太阳 / 月亮 / 上升）
    profiles = []
    for label, sg in (("太阳", sun), ("月亮", moon), ("上升", asc if has_asc else None)):
        p = SIGN_PROFILE.get(sg) if sg else None
        if p:
            profiles.append({"名": "%s · %s座" % (label, sg), "档案": p})

    return {
        "一句话": one,
        "三支柱": {"标题": "你的三大支柱", "列表": pillars},
        "性格拼图": {"标题": "你的性格拼图", "列表": puzzle},
        "人生重心": {"标题": "你的人生重心在哪", "列表": focus},
        "关键线索": key_clue,
        "元素配比": {"标题": "你的能量配比", "要点": e_txt, "明细": elem},
        "关系张力": {"标题": "你身上的主要张力", "列表": tension},
        "实用档案": {"标题": "你的星座档案", "列表": profiles},
        "术语": [("太阳星座", "你的核心自我和人生主题。"),
                 ("月亮星座", "你的情绪需求和内心世界。"),
                 ("上升星座", GLOSSARY["上升星座"]),
                 ("宫位", "星盘里的十二个生活领域，比如第4宫管家庭、第10宫管事业。"),
                 ("相位", GLOSSARY["相位"])],
    }


