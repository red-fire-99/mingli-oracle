def _liunian_note(r):
    """流年：只有一年，但要说清它在整盘里的位置。"""
    ln = r.get("流年")
    if not ln:
        return None
    cur = ln.get("当前大限", "")
    # 流年命宫给的是「午宫」这种「地支+宫」形式，
    # 而 PALACE_MEANING 的键是宫名（「命宫」/「财帛」…），
    # 直接去掉「宫」去查必然查不到 —— 所以用地支反查回宫名。
    lnz = ln.get("流年命宫") or ""
    ln_zh = lnz[:-1] if lnz.endswith("宫") else lnz
    pal_name = next((p["宫名"] for p in r["十二宫"] if p["地支"] == ln_zh), "")
    # 当前大限是「田宅·寅」，取前半段宫名
    dx_pal = (cur.split("·")[0] if cur else "")
    return {
        "年": ln.get("年"),
        "干支": ln.get("干支"),
        "虚岁": ln.get("虚岁"),
        "流年命宫": lnz,
        "流年命宫名": pal_name,
        "当前大限": cur,
        "当前大限宫": dx_pal,
        "说明": LIUNIAN_NOTE,
        "命宫含义": PALACE_MEANING.get(pal_name, ""),
        "大限含义": PALACE_MEANING.get(dx_pal, ""),
        "大限主题": DAXIAN_THEME.get(dx_pal, ""),
    }


def _sihua_list(r):
    """四化逐项：禄权科忌各落在哪一宫、代表什么。"""
    h = r.get("四化") or {}
    out = []
    for key in ("化禄", "化权", "化科", "化忌"):
        star = h.get(key)
        if not star:
            continue
        nm, _h4 = _split_star(star)
        # 四化跟着星走，星在哪一宫，那一宫就被强化
        pal = next((p for p in r["十二宫"]
                    if any(_split_star(s)[0] == nm for s in p["星曜"])), None)
        role, mean = SIHUA_ROLE.get(key, ("", ""))
        out.append({
            "化": key,
            "星": star,
            "宫位": pal["宫名"] if pal else "",
            "宫位含义": PALACE_MEANING.get(pal["宫名"], "") if pal else "",
            "角色": role,
            "要点": mean,
        })
    return out


