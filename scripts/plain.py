def bazi_plain(r):
    """把八字排盘结果翻译成白话，返回结构化 dict。"""
    dm = r["日主"]["干"]
    wx = r["日主"]["五行"]
    archetype, one_line, detail = DAY_MASTER[dm]

    # 性格
    strength = r["日主强弱"]["判定"]
    s_head, s_body = STRENGTH[strength]

    # 十神标签（取透干的，最多 3 个）
    tags = []
    for d in r["柱详解"]:
        if d["柱"] == "日":
            continue
        ss = d["干十神"]
        if ss in SHISHEN and ss not in [t[0] for t in tags]:
            tags.append((ss, SHISHEN[ss]))
    tags = tags[:3]

    # 五行
    pct = r["五行统计"]
    top = max(pct, key=pct.get)
    low = min(pct, key=pct.get)
    wuxing_txt = ("你的「%s」最旺，说明你%s。"
                  % (top, WUXING_HIGH[top]))
    if pct[low] < 8:
        wuxing_txt += "「%s」偏少，%s。" % (low, WUXING_LOW[low])

    # 神煞
    lucky = []
    for x in r["神煞"]:
        info = SHENSHA.get(x["神煞"])
        if info and info[0] not in [t[0] for t in lucky]:
            lucky.append(info)
    lucky = lucky[:4]

    # 当前大运：按当前年份定位所属大运，取「大运自身」的十神（不能用流年十神）
    dayun_now = None
    cur_year = int(r.get("当前时间", "2026"))
    cur_ln = next((x for x in r["流年"] if x["年"] == cur_year), None)
    if cur_ln is None and r["流年"]:
        cur_ln = r["流年"][len(r["流年"]) // 2]
    if cur_ln and cur_ln.get("大运"):
        gz = cur_ln["大运"]
        dy = next((d for d in r["大运"]["列表"] if d["干支"] == gz), None)
        ss = dy["十神"] if dy else ""
        dayun_now = {
            "干支": gz,
            "十神": ss,
            "主题": DAYUN_THEME.get(ss, "平稳过渡"),
            "年份": cur_year,
        }

    # 一句话速写
    summary = "你的底子是「%s」型的人——%s" % (archetype, one_line)

    # 生肖
    shengxiao = None
    yz = r["四柱"]["年"]
    if yz and yz != "未知":
        sx_name = ZHI_TO_SX.get(yz[1])
        if sx_name and sx_name in SHENGXIAO:
            trait, s_colors, s_nums = SHENGXIAO[sx_name]
            shengxiao = {"生肖": sx_name, "特质": trait, "幸运色": s_colors, "幸运数字": s_nums}

    # 开运指南：按喜用神给可落地的建议
    luck = None
    xiyong = r["日主强弱"]["喜用神"]
    if xiyong:
        buckets = {"颜色": [], "方位": [], "数字": [], "行业": [], "饰品": [], "日常": []}
        for wx in xiyong:
            d = WUXING_LUCK.get(wx)
            if not d:
                continue
            for k in buckets:
                buckets[k].append(d[k])
        luck = {"五行": "、".join(xiyong)}
        luck.update({k: "；".join(v) for k, v in buckets.items()})

    return {
        "一句话": summary,
        "性格底色": {"标题": "你的性格底色", "要点": one_line, "补充": detail},
        "做事方式": {"标题": "你的做事方式", "要点": s_head, "补充": s_body},
        "天生擅长": {"标题": "你天生擅长什么",
                     "标签": [{"名": t[1][0], "说明": t[1][1]} for t in tags]},
        "能量分布": {"标题": "你的能量分布", "要点": wuxing_txt,
                     "喜用": r["日主强弱"]["喜用神"]},
        "运气加成": {"标题": "你的运气加成",
                     "标签": [{"名": t[0], "说明": t[1]} for t in lucky]},
        "生肖": shengxiao,
        "开运指南": luck,
        "当前阶段": dayun_now,
        "术语": [("日主", GLOSSARY["日主/日干"]), ("十神", GLOSSARY["十神"]),
                 ("大运", GLOSSARY["大运"]), ("神煞", GLOSSARY["神煞"]),
                 ("喜用神", GLOSSARY["喜用神"])],
    }


