def _shensha_list(r):
    """神煞逐条解读。

    吉凶分类不再靠「名字里有没有 煞/刃/孤/寡」猜 ——
    那套判据把亡神判成吉（实际不吉）、把寡宿判成凶（其实中性）。
    现在逐个查 SHENSHA_KIND；表里没有的标成「未知」而不是默认吉 ——
    默认吉等于「没查过就说好」，方向错了。
    """
    out = []
    for s in (r.get("神煞") or []):
        name = s["神煞"]
        kind = SHENSHA_KIND.get(name, "")
        out.append({
            "神煞": name,
            "查法": s.get("查法", ""),
            "落支": s.get("落支", ""),
            "位置": s.get("位置", ""),
            "说明": s.get("说明", ""),
            "类别": kind,
            "类别说明": SHENSHA_KIND_NOTE.get(kind, "未归类"),
        })
    # 未归类的要能被发现，不能静默当成吉
    unknown = [x["神煞"] for x in out if not x["类别"]]
    return {"标题": "你命里的神煞", "列表": out,
            "未归类": unknown,
            "计数": {"助你": len([x for x in out if x["类别"] == "ji"]),
                     "中性": len([x for x in out if x["类别"] == "xu"]),
                     "留意": len([x for x in out if x["类别"] == "xiong"]),
                     "未归类": len(unknown)}}


def _shishen_list(r):
    """十神分布：哪个最多，就勾勒出你人生的主要关系模式。

    干上的十神权重高于藏干（藏干要分本气/中气/余气），
    这里只数「个数」不给百分比，避免造出一个看起来精确、
    实际权重不对的数字。
    """
    count = {}
    for c in (r.get("柱详解") or []):
        g = c.get("干十神")
        if g and g != "日主":
            count[g] = count.get(g, 0) + 1
    z_count = {}
    for c in (r.get("柱详解") or []):
        for z in (c.get("支藏干") or []):
            ss = z.get("十神")
            if ss:
                z_count[ss] = z_count.get(ss, 0) + 1

    total = sum(count.values()) + sum(z_count.values())
    items = []
    # 首次出现顺序：先「干上」的顺序，再补「只在藏干里」的。
    # 不用 sorted(set(...)) —— 那是无序的，而并列最高时要靠顺序决定
    # 先报哪一个，JS 侧只能靠同样的插入序来对齐。
    order = list(count.keys())
    for k in z_count:
        if k not in order:
            order.append(k)
    for ss in order:
        gan = count.get(ss, 0)
        zhi = z_count.get(ss, 0)
        items.append({
            "十神": ss,
            "干上": gan,
            "藏干": zhi,
            "合计": gan + zhi,
            "占比": round((gan + zhi) / total * 100, 1) if total else 0,
            "说明": SHISHEN_COUNT_NOTE.get(ss, ""),
        })
    items.sort(key=lambda x: -x["合计"])

    # 并列最高时要全部列出。八个字摊到十种十神上，
    # 出现四五个并列第一是常态 —— 只报一个会让人以为
    # 「我最重要的是偏印」，而实际上偏印/正印/正官/比肩一样多。
    top_n = items[0]["合计"] if items else 0
    tied = [x["十神"] for x in items if x["合计"] == top_n]

    # 组合：取「合计 >= 2」的前几个，配对看
    pairs = []
    top = [x["十神"] for x in items if x["合计"] >= 2][:4]
    for i in range(len(top)):
        for j in range(i + 1, len(top)):
            txt = SHISHEN_PAIR.get("%s|%s" % (top[i], top[j])) \
                  or SHISHEN_PAIR.get("%s|%s" % (top[j], top[i]))
            if txt:
                pairs.append({"组合": "%s + %s" % (top[i], top[j]), "说明": txt})

    if len(tied) == 1:
        lead = {"名": tied[0], "并列": False,
                "说明": SHISHEN_COUNT_NOTE.get(tied[0], "")}
    else:
        lead = {
            "名": "、".join(tied),
            "并列": True,
            "说明": "你的十神没有单一主角——%s 各占 %d 个。"
                    "这类盘的特点是均衡：适应面广，什么环境都能待。"
                    "代价是不容易说出「我最想要什么」，"
                    "因为没有一样明显压过其他。"
                    % ("、".join(tied), top_n),
        }
    return {"标题": "你的十神分布", "明细": items, "组合": pairs,
            "最多": lead["名"], "并列": lead["并列"],
            "最多说明": lead["说明"],
            "并列项": tied}




