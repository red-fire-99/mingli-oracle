def headline(data):
    """从三盘提炼一句总览，放在页面最上方。"""
    bits = []
    if "八字" in data:
        b = data["八字"]
        bits.append("八字日主「%s」，%s" % (b["日主"]["干"], DAY_MASTER[b["日主"]["干"]][0]))
    if "紫微" in data:
        z = data["紫微"]
        ming = next((p for p in z["十二宫"] if p["是否命宫"]), None)
        mains = [s.split("·")[0] for s in ming["星曜"]] if ming else []
        mains = [s for s in mains if s in ZIWEI_STAR]
        if mains:
            bits.append("紫微命宫主星「%s」" % mains[0])
    if "占星" in data:
        a = data["占星"]
        bits.append("太阳%s·月亮%s" % (a["太阳星座"], a["月亮星座"]))
    return " ｜ ".join(bits)


