def ziwei_plain(r):
    ming = next((p for p in r["十二宫"] if p["是否命宫"]), None)
    stars = [s.split("·")[0] for s in ming["星曜"]] if ming else []
    mains = [s for s in stars if s in ZIWEI_STAR]

    if mains:
        head = ZIWEI_STAR[mains[0]]["核心"]
        summary = "你的命宫主星是「%s」——%s，%s。" % (mains[0], head[0], head[1])
    else:
        # 空宫：借对宫
        opp = {"子": "午", "丑": "未", "寅": "申", "卯": "酉", "辰": "戌", "巳": "亥",
               "午": "子", "未": "丑", "申": "寅", "酉": "卯", "戌": "辰", "亥": "巳"}
        oz = opp.get(ming["地支"], "") if ming else ""
        op = next((p for p in r["十二宫"] if p["地支"] == oz), None)
        o_mains = [s.split("·")[0] for s in op["星曜"]] if op else []
        o_mains = [s for s in o_mains if s in ZIWEI_STAR]
        if o_mains:
            head = ZIWEI_STAR[o_mains[0]]["核心"]
            summary = ("你的命宫是「空宫」，要借对宫的「%s」来论——%s，%s。"
                       % (o_mains[0], head[0], head[1]))
            mains = o_mains
        else:
            summary = "你的命宫是空宫，性格可塑性很强，环境对你的影响比较大。"

    # 其他宫位主星
    def palace_stars(name):
        p = next((x for x in r["十二宫"] if x["宫名"] == name), None)
        if not p:
            return []
        return [s.split("·")[0] for s in p["星曜"] if s.split("·")[0] in ZIWEI_STAR]

    career = palace_stars("官禄")
    wealth = palace_stars("财帛")
    love = palace_stars("夫妻")

    def brief(stars_list, dim, fallback):
        if not stars_list:
            return fallback
        s = stars_list[0]
        return "「%s」——%s，%s" % (s, ZIWEI_STAR[s]["核心"][1], ZIWEI_STAR[s][dim])

    # 四化提醒
    h = r["四化"]
    hua_note = ("生年四化中，你的「%s」化忌——这一块是你这辈子要重点面对的课题；"
                "「%s」化禄——这一块天生有福气、有资源。"
                % (h["化忌"], h["化禄"]))

    # 五行局开运（紫微的五行局同样可以套用五行开运表）
    ju_wx = (r.get("五行局") or "")[:1]
    ju_luck = None
    if ju_wx in WUXING_LUCK:
        ju_luck = {"五行": ju_wx, "局": r.get("五行局", "")}
        ju_luck.update(WUXING_LUCK[ju_wx])

    return {
        "一句话": summary,
        "主星": mains[0] if mains else None,
        "事业方向": {"标题": "事业方向",
                     "要点": brief(career, "事业", "官禄宫无主星，事业方向灵活，跟着兴趣走就好。")},
        "财运模式": {"标题": "财运模式",
                     "要点": brief(wealth, "财运", "财帛宫无主星，财运随大环境起伏，宜稳不宜赌。")},
        "感情模式": {"标题": "感情模式",
                     "要点": brief(love, "感情", "夫妻宫无主星，感情模式偏自由，随缘而遇。")},
        "四化提醒": {"标题": "人生课题与福气", "要点": hua_note},
        "开运指南": ju_luck,
        "术语": [("命宫", GLOSSARY["命宫"]), ("主星", GLOSSARY["主星"]),
                 ("四化", GLOSSARY["四化"]), ("大限", GLOSSARY["大限"])],
    }


